"""Tests for src/rag.py."""

import pytest

from src import rag


def test_lora_query_retrieves_lora_note():
    top_doc, _ = rag.retrieve("what is LoRA fine tuning", top_k=1)[0]
    assert top_doc["id"] == "lora"


def test_injection_query_retrieves_defense_note():
    top_doc, _ = rag.retrieve("how do I stop prompt injection attacks", top_k=1)[0]
    assert top_doc["id"] == "defense"


def test_scores_are_bounded_and_ranked():
    ranked = rag.retrieve("speculative decoding latency", top_k=3)
    scores = [score for _, score in ranked]
    assert all(0.0 <= s <= 1.0 for s in scores)
    assert scores == sorted(scores, reverse=True)


def test_empty_query_scores_zero():
    ranked = rag.retrieve("", top_k=3)
    assert all(score == 0.0 for _, score in ranked)


def test_cosine_of_identical_vectors_is_one():
    vec = {"a": 0.5, "b": 0.25}
    assert rag._cosine(vec, vec) == pytest.approx(1.0)


def test_stub_answer_is_labeled():
    ranked = rag.retrieve("what is LoRA", top_k=1)
    answer = rag.assemble_answer("what is LoRA", ranked)
    assert "STUB" in answer
    assert "not generated by a model" in answer
