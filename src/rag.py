def tokenize(text):
    return re.findall(r"[a-z0-9]+", text.lower())


def _idf(documents):
    """Smoothed inverse document frequency for every word."""
    n = len(documents)
    doc_freq = Counter()
    for doc in documents:
        doc_freq.update(set(tokenize(doc["text"])))
    return {word: math.log((n + 1) / (freq + 1)) + 1.0
            for word, freq in doc_freq.items()}


def _vector(text, idf):
    """TF-IDF vector (sparse dict) for one piece of text."""
    words = tokenize(text)
    counts = Counter(words)
    total = len(words) or 1
    return {word: (count / total) * idf.get(word, 0.0)
            for word, count in counts.items()}


def _cosine(vec_a, vec_b):
    """Cosine similarity between two sparse vectors, in [0, 1]."""
    dot = sum(vec_a[w] * vec_b[w] for w in set(vec_a) & set(vec_b))
    norm_a = math.sqrt(sum(v * v for v in vec_a.values()))
    norm_b = math.sqrt(sum(v * v for v in vec_b.values()))
    if norm_a == 0.0 or norm_b == 0.0:
        return 0.0
    return dot / (norm_a * norm_b)


def retrieve(query, documents=DOCUMENTS, top_k=2):
    """Rank documents by TF-IDF cosine similarity to the query."""
    idf = _idf(documents)
    query_vec = _vector(query, idf)
    scored = []
    for doc in documents:
        score = _cosine(query_vec, _vector(doc["text"], idf))
        scored.append((doc, score))
    scored.sort(key=lambda pair: -pair[1])
    return scored[:top_k]


def assemble_answer(query, retrieved):
    """Stub answer assembly — NOT model generation, labeled as such."""
    notes = "\n".join(f"- [{doc['title']}] {doc['text']}"
                      for doc, _ in retrieved)
    return ("[STUB ANSWER — assembled from retrieved notes, "
            "not generated by a model]\n"
            f"Question: {query}\n"
            f"Retrieved context:\n{notes}\n"
            "A real system would now pass the question plus these "
            "notes to a language model for the final answer.")


def ascii_bars(pairs, width=40):
    top = max(score for _, score in pairs) or 1.0
    lines = []
    for label, score in pairs:
        bar = "#" * max(1, int(round(score / top * width))) if score > 0 else ""
        lines.append(f"{label:>28} | {bar} {score:.3f}")
    return "\n".join(lines)


def main():
    for query in ["how do I stop prompt injection attacks",
                  "what is LoRA fine tuning"]:
        ranked = retrieve(query, top_k=3)
        print(f"Query: {query}")
        print(ascii_bars([(doc["title"], score) for doc, score in ranked]))
        print(assemble_answer(query, ranked[:2]))
        print("-" * 70)


if __name__ == "__main__":
    main()
