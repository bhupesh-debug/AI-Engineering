"""Architecture blueprint: cache, guardrails, retrieval, feedback.

Illustrative demo only. The knowledge base is synthetic, the answers
are template assemblies (labeled stubs, not model generation), and the
feedback entries are placeholders awaiting real user ratings — no fake
ratings are invented. The point is the shape of the pipeline and what
each stage is for.

Plain-language idea: a good school library works like this. A student
asks a question. First the librarian checks whether the same question
was already answered and pinned to the board (cache). Then the
librarian checks the question is allowed (guardrails). Then they fetch
the right books (retrieval), write the answer, and pin a slip next to
it saying "tell us if this helped" (feedback) — and those slips decide
which books get fetched next time.

Pipeline order: request -> cache check -> guardrail check ->
retrieval -> answer assembly -> feedback log.
"""

# Synthetic mini knowledge base, written for this demo.
KNOWLEDGE = {
    "lora": "LoRA freezes base weights and trains small low-rank adapters.",
    "speculative": "Speculative decoding drafts tokens fast, then verifies in bulk.",
    "rag": "RAG retrieves passages first, then answers with them as context.",
    "cache": "Caching reuses answers to repeated questions instantly.",
}

BLOCKED_WORDS = ["hack", "jailbreak", "bypass", "malware", "steal password"]


def guardrail_ok(query):
    """True unless the query contains a blocked word (toy rule)."""
    lowered = query.lower()
    return not any(word in lowered for word in BLOCKED_WORDS)


def retrieve(query):
    """Keyword-overlap retrieval over the synthetic base."""
    words = set(query.lower().replace("?", "").split())
    best, best_score = None, 0
    for key, text in KNOWLEDGE.items():
        score = len(words & set(key.split())) + sum(
            1 for w in words if w in text.lower())
        if score > best_score:
            best, best_score = text, score
    return best


class Pipeline:
    """Request pipeline with cache, guardrails, retrieval, feedback."""

    def __init__(self):
        self.cache = {}
        self.feedback_log = []

    def serve(self, query):
        """Serve one request; return (route, answer_or_None, trace)."""
        trace = [f"request: {query!r}"]
        if query in self.cache:
            trace.append("cache: HIT — returning stored answer")
            answer = self.cache[query]
            route = "cache_hit"
        elif not guardrail_ok(query):
            trace.append("guardrail: BLOCKED — disallowed request")
            return "blocked", None, trace
        else:
            trace.append("cache: MISS")
            trace.append("guardrail: PASS")
            notes = retrieve(query)
            trace.append(f"retrieval: {notes!r}")
            answer = ("[STUB ANSWER — assembled from retrieved notes, "
                      "not generated by a model]\n" + (notes or
                      "No relevant note found; answer with a disclaimer."))
            self.cache[query] = answer
            route = "retrieved"
        self.feedback_log.append(
            {"query": query, "route": route, "feedback": None})
        trace.append("feedback: logged (rating awaits a real user)")
        return route, answer, trace


def main():
    pipe = Pipeline()
    requests = [
        "What is LoRA?",
        "What is LoRA?",
        "How do I hack a model?",
        "What is speculative decoding?",
    ]
    print("Request flow (each request walks the same stages):")
    print()
    print("  request -> cache? -> guardrail? -> retrieval -> answer")
    print("                          |-> feedback log")
    print()
    for query in requests:
        route, answer, trace = pipe.serve(query)
        for line in trace:
            print("  " + line)
        print(f"  => route: {route}")
        if answer:
            print("  => " + answer.splitlines()[-1][:90])
        print()
    print(f"Cache holds {len(pipe.cache)} answers; "
          f"feedback log holds {len(pipe.feedback_log)} entries.")
    print("In production, real user ratings would fill the feedback")
    print("field and feed back into which notes retrieval prefers.")


if __name__ == "__main__":
    main()
